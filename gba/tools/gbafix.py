#!/usr/bin/env python3
"""
Fix up a GBA ROM header (logo, title, codes, complement checksum).

Minimal replacement for devkitPro's gbafix, used when building without
devkitARM. Usage: gbafix.py rom.gba [--title T] [--code CODE] [--maker MK]
"""
import argparse

LOGO = bytes([
    0x24, 0xFF, 0xAE, 0x51, 0x69, 0x9A, 0xA2, 0x21, 0x3D, 0x84, 0x82, 0x0A,
    0x84, 0xE4, 0x09, 0xAD, 0x11, 0x24, 0x8B, 0x98, 0xC0, 0x81, 0x7F, 0x21,
    0xA3, 0x52, 0xBE, 0x19, 0x93, 0x09, 0xCE, 0x20, 0x10, 0x46, 0x4A, 0x4A,
    0xF8, 0x27, 0x31, 0xEC, 0x58, 0xC7, 0xE8, 0x33, 0x82, 0xE3, 0xCE, 0xBF,
    0x85, 0xF4, 0xDF, 0x94, 0xCE, 0x4B, 0x09, 0xC1, 0x94, 0x56, 0x8A, 0xC0,
    0x13, 0x72, 0xA7, 0xFC, 0x9F, 0x84, 0x4D, 0x73, 0xA3, 0xCA, 0x9A, 0x61,
    0x58, 0x97, 0xA3, 0x27, 0xFC, 0x03, 0x98, 0x76, 0x23, 0x1D, 0xC7, 0x61,
    0x03, 0x04, 0xAE, 0x56, 0xBF, 0x38, 0x84, 0x00, 0x40, 0xA7, 0x0E, 0xFD,
    0xFF, 0x52, 0xFE, 0x03, 0x6F, 0x95, 0x30, 0xF1, 0x97, 0xFB, 0xC0, 0x85,
    0x60, 0xD6, 0x80, 0x25, 0xA9, 0x63, 0xBE, 0x03, 0x01, 0x4E, 0x38, 0xE2,
    0xF9, 0xA2, 0x34, 0xFF, 0xBB, 0x3E, 0x03, 0x44, 0x78, 0x00, 0x90, 0xCB,
    0x88, 0x11, 0x3A, 0x94, 0x65, 0xC0, 0x7C, 0x63, 0x87, 0xF0, 0x3C, 0xAF,
    0xD6, 0x25, 0xE4, 0x8B, 0x38, 0x0A, 0xAC, 0x72, 0x21, 0xD4, 0xF8, 0x07
])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("rom")
    ap.add_argument("--title", default="")
    ap.add_argument("--code", default="")
    ap.add_argument("--maker", default="")
    args = ap.parse_args()

    rom = bytearray(open(args.rom, "rb").read())
    if len(rom) < 0xC0:
        rom.extend(b"\0" * (0xC0 - len(rom)))
    rom[0x04:0xA0] = LOGO
    if args.title:
        rom[0xA0:0xAC] = args.title.encode("ascii")[:12].ljust(12, b"\0")
    if args.code:
        rom[0xAC:0xB0] = args.code.encode("ascii")[:4].ljust(4, b"0")
    if args.maker:
        rom[0xB0:0xB2] = args.maker.encode("ascii")[:2].ljust(2, b"0")
    rom[0xB2] = 0x96
    rom[0xB3] = 0x00
    rom[0xB4] = 0x00
    chk = 0
    for i in range(0xA0, 0xBD):
        chk += rom[i]
    rom[0xBD] = (-(chk + 0x19)) & 0xFF
    # Pad to a 4-byte boundary (some flashcart loaders dislike odd sizes).
    while len(rom) % 4:
        rom.append(0xFF)
    open(args.rom, "wb").write(rom)


if __name__ == "__main__":
    main()
